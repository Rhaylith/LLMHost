using System.Text.RegularExpressions;
using LLMHostProject.Core;

namespace LLMHostProject.Inference;

/// <summary>Turns the MoE / tensor-placement options into the list of (pattern, buffer) rules llama.cpp understands.</summary>
public static class TensorOverrides
{
    /// <summary>Regex for the expert weights (up / down / gate, also the fused and "chunked" names) of the first <paramref name="layers"/> layers; -1 = every layer.</summary>
    public static string MoePattern(int layers)
    {
        const string experts = @"ffn_(up|down|gate|gate_up)(_ch)?_exps\.";
        if (layers < 0) return @"\." + experts;
        return @"blk\.(" + string.Join("|", Enumerable.Range(0, layers)) + @")\." + experts;
    }

    /// <summary>All rules in force: the explicit ones plus the one generated by <see cref="LoadOptions.MoeCpuLayers"/>.</summary>
    public static List<TensorOverrideSetting> Effective(LoadOptions o)
    {
        var list = new List<TensorOverrideSetting>();
        if (o.MoeCpuLayers != 0) list.Add(new TensorOverrideSetting { Pattern = MoePattern(o.MoeCpuLayers), Buffer = "CPU" });
        if (o.TensorOverrides != null)
            list.AddRange(o.TensorOverrides.Where(t => !string.IsNullOrWhiteSpace(t.Pattern)));
        return list;
    }

    public static bool IsHostBuffer(string buffer) => buffer.Equals("CPU", StringComparison.OrdinalIgnoreCase);

    /// <summary>Compiled rules that send a tensor to system memory (what the memory estimate needs).</summary>
    public static List<Regex> HostRules(LoadOptions o)
    {
        var rules = new List<Regex>();
        foreach (var t in Effective(o))
        {
            if (!IsHostBuffer(t.Buffer)) continue;
            try { rules.Add(new Regex(t.Pattern, RegexOptions.CultureInvariant)); } catch (ArgumentException) { /* reported by validation */ }
        }
        return rules;
    }

    /// <summary>Problems with the placement options (for validation messages).</summary>
    public static IEnumerable<string> Check(LoadOptions o)
    {
        if (o.MoeCpuLayers < -1 || o.MoeCpuLayers > 1000) yield return "MoE CPU layers must be -1 (all), 0 (off) or a layer count.";
        if (o.MoeExpertCount < 0 || o.MoeExpertCount > 1024) yield return "MoE expert count must be 0 (model default) or the number of experts to use.";
        foreach (var t in o.TensorOverrides ?? new())
        {
            if (string.IsNullOrWhiteSpace(t.Pattern)) { yield return "A tensor override has an empty pattern."; continue; }
            string? bad = null;
            try { _ = new Regex(t.Pattern); } catch (ArgumentException ex) { bad = ex.Message; }
            if (bad != null) yield return $"Tensor pattern '{t.Pattern}' is not a valid regular expression: {bad}";
            if (string.IsNullOrWhiteSpace(t.Buffer)) yield return $"Tensor pattern '{t.Pattern}' has no buffer.";
        }
    }
}
